LABELS["kz"] = LABELS["ru"]  # Kazakh uses same labels as Russian for now


def _get_labels(lang: str) -> dict:
    return LABELS.get(lang, LABELS["ru"])


def _fact_text(fact) -> str:
    """Extract text from a fact (string or {text: ...} dict)."""
    if isinstance(fact, str):
        return fact.strip()
    if isinstance(fact, dict):
        return (fact.get("text") or "").strip()
    return str(fact or "").strip()


def _fact_source(fact) -> str:
    if isinstance(fact, dict):
        return (fact.get("source") or "").strip()
    return ""


def _fact_conflict(fact) -> tuple:
    """Return (has_conflict: bool, details: str)."""
    if isinstance(fact, dict):
        return bool(fact.get("has_conflict")), (fact.get("conflict_details") or "")
    return False, ""


