def generate_docx(data: dict, language: str = "ru") -> bytes:
    """Generate a professional DOCX from NeuralDocs output. Returns DOCX bytes."""
    L = _get_labels(language)
    doc_data = data.get("document_extended") or data.get("document", {})
    meta = data.get("metadata", {})

    doc = Document()

    # ── Styles ────────────────────────────────────────────────────────────
    style = doc.styles['Normal']
    style.font.name = 'Calibri'
    style.font.size = Pt(11)
    style.paragraph_format.space_after = Pt(6)

    # ── Cover page ────────────────────────────────────────────────────────
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.space_before = Pt(100)
    run = p.add_run("🧠 NeuralDocs AI")
    run.font.size = Pt(32)
    run.font.color.rgb = RGBColor(0x4F, 0x46, 0xE5)
    run.bold = True

    p2 = doc.add_paragraph()
    p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run2 = p2.add_run(L["title"])
    run2.font.size = Pt(18)
    run2.font.color.rgb = RGBColor(0x1F, 0x29, 0x37)

    # Overview on cover
    overview = ""
    if isinstance(doc_data.get("project_overview"), str):
        overview = doc_data["project_overview"]
    elif isinstance(doc_data.get("project_overview"), dict):
        overview = doc_data["project_overview"].get("text", "")
    if overview:
        p3 = doc.add_paragraph()
        p3.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p3.space_before = Pt(20)
        run3 = p3.add_run(overview)
        run3.font.size = Pt(11)
        run3.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)

    # Date & model
    p4 = doc.add_paragraph()
    p4.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p4.space_before = Pt(30)
    now = datetime.now().strftime("%d.%m.%Y %H:%M")
    run4 = p4.add_run(f"{L['generated']}: {now}\n{L['model']}: {meta.get('model_name', 'N/A')}")
    run4.font.size = Pt(9)
    run4.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)

    doc.add_page_break()

    # ── Helper: add section ──────────────────────────────────────────────
    def add_heading(title: str):
        h = doc.add_heading(title, level=2)
        for run in h.runs:
            run.font.color.rgb = RGBColor(0x4F, 0x46, 0xE5)

    def add_scalar(field):
        txt = _fact_text(field)
        if not txt:
            p = doc.add_paragraph(L["no_data"])
            p.runs[0].font.color.rgb = RGBColor(0x6B, 0x72, 0x80)
            p.runs[0].italic = True
            return

        p = doc.add_paragraph(txt)
        src = _fact_source(field)
        if src:
            run = p.add_run(f"  [{src}]")
            run.font.size = Pt(8)
            run.font.color.rgb = RGBColor(0x1E, 0x40, 0xAF)

        has_c, c_detail = _fact_conflict(field)
        if has_c and c_detail:
            cp = doc.add_paragraph()
            run = cp.add_run(f"⚠ {L['conflict_label']}: {c_detail}")
            run.font.size = Pt(9)
            run.font.color.rgb = RGBColor(0x92, 0x40, 0x0E)
            # Yellow highlight for conflict
            from docx.oxml.ns import qn
            from docx.oxml import OxmlElement
            shading = OxmlElement('w:shd')
            shading.set(qn('w:fill'), 'FEF3C7')
            shading.set(qn('w:val'), 'clear')
            run._element.rPr.append(shading)

    def add_list(items):
        if not items:
            p = doc.add_paragraph(L["no_data"])
            p.runs[0].font.color.rgb = RGBColor(0x6B, 0x72, 0x80)
            p.runs[0].italic = True
            return

        for item in items:
            txt = _fact_text(item)
            if not txt:
                continue

            p = doc.add_paragraph(txt, style='List Bullet')
            src = _fact_source(item)
            if src:
                run = p.add_run(f"  [{src}]")
                run.font.size = Pt(8)
                run.font.color.rgb = RGBColor(0x1E, 0x40, 0xAF)

            has_c, c_detail = _fact_conflict(item)
            if has_c and c_detail:
                run = p.add_run(f"\n⚠ {c_detail}")
                run.font.size = Pt(8)
                run.font.color.rgb = RGBColor(0x92, 0x40, 0x0E)

    # ── Sections ─────────────────────────────────────────────────────────
    add_heading(L["project_overview"])
    ov = doc_data.get("project_overview")
    if isinstance(ov, str):
        doc.add_paragraph(ov or L["no_data"])
    else:
        add_scalar(ov)

    add_heading(L["goals"])
    add_list(doc_data.get("goals"))

    add_heading(L["requirements"])
    add_list(doc_data.get("requirements"))

    add_heading(L["technical_solution"])
    add_scalar(doc_data.get("technical_solution"))

    add_heading(L["architecture"])
    add_scalar(doc_data.get("architecture"))

    add_heading(L["team"])
    add_list(doc_data.get("team"))

    add_heading(L["timeline_budget"])
    tl = doc_data.get("timeline")
    bg = doc_data.get("budget")

    # Timeline
    p = doc.add_paragraph()
    run = p.add_run(f"{L['timeline']}: ")
    run.bold = True
    run = p.add_run(_fact_text(tl) or L["no_data"])
    tl_src = _fact_source(tl)
    if tl_src:
        run = p.add_run(f"  [{tl_src}]")
        run.font.size = Pt(8)
        run.font.color.rgb = RGBColor(0x1E, 0x40, 0xAF)

    tl_c, tl_cd = _fact_conflict(tl)
    if tl_c and tl_cd:
        cp = doc.add_paragraph()
        run = cp.add_run(f"⚠ {tl_cd}")
        run.font.size = Pt(9)
        run.font.color.rgb = RGBColor(0x92, 0x40, 0x0E)

    # Budget
    p = doc.add_paragraph()
    run = p.add_run(f"{L['budget']}: ")
    run.bold = True
    run = p.add_run(_fact_text(bg) or L["no_data"])
    bg_src = _fact_source(bg)
    if bg_src:
        run = p.add_run(f"  [{bg_src}]")
        run.font.size = Pt(8)
        run.font.color.rgb = RGBColor(0x1E, 0x40, 0xAF)

    bg_c, bg_cd = _fact_conflict(bg)
    if bg_c and bg_cd:
        cp = doc.add_paragraph()
        run = cp.add_run(f"⚠ {bg_cd}")
        run.font.size = Pt(9)
        run.font.color.rgb = RGBColor(0x92, 0x40, 0x0E)

    add_heading(L["risks"])
    add_list(doc_data.get("risks"))

    # ── Metadata ─────────────────────────────────────────────────────────
    doc.add_page_break()
    add_heading(L["metadata"])
    meta_lines = [
        f"{L['files']}: {(meta.get('llm_calls', 1)) - 1}",
        f"{L['tokens']}: {meta.get('total_tokens', 0):,}",
        f"{L['duration']}: {meta.get('duration_ms', 0):,} ms",
        f"{L['model']}: {meta.get('model_name', 'N/A')}",
    ]
    for line in meta_lines:
        p = doc.add_paragraph(line)
        p.runs[0].font.size = Pt(9)
        p.runs[0].font.color.rgb = RGBColor(0x6B, 0x72, 0x80)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
